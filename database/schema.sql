-- =============================================================================
--  INVENTARIO DE ACTIVOS DE TI - COLEGIO AYACUCHO (Ayacucho, Perú)
--  Script DDL equivalente al modelo JPA (PostgreSQL 12 o superior)
--
--  Uso: pgAdmin 4  ->  Databases > cole > Query Tool > abrir este
--  archivo y ejecutar (F5). Es idempotente: puede ejecutarse varias veces.
--
--  Nota: la aplicación usa spring.jpa.hibernate.ddl-auto=update, por lo que
--  también puede crear el esquema sola. Este script sirve para tener el
--  esquema bajo control manual y versionado.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. USUARIOS DEL SISTEMA
--    Roles: ADMIN (todo) | TECNICO (consulta y edita activos)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username               VARCHAR(50)  NOT NULL,
    password               VARCHAR(100) NOT NULL,           -- hash BCrypt (60 caracteres)
    nombre_completo        VARCHAR(120) NOT NULL,
    rol                    VARCHAR(20)  NOT NULL,
    activo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    debe_cambiar_password  BOOLEAN      NOT NULL DEFAULT TRUE, -- obliga a cambiar la clave temporal
    CONSTRAINT uq_usuarios_username UNIQUE (username),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'TECNICO'))
);

-- -----------------------------------------------------------------------------
-- 2. CATÁLOGO DE TIPOS DE ACTIVO
--    Servidor, Switch, Punto de acceso, Firewall, NAS, UPS, PC, Impresora
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tipos_activo (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(60) NOT NULL,
    CONSTRAINT uq_tipos_activo_nombre UNIQUE (nombre)
);

-- -----------------------------------------------------------------------------
-- 3. CATÁLOGO DE UBICACIONES FÍSICAS DEL COLEGIO
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ubicaciones (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT uq_ubicaciones_nombre UNIQUE (nombre)
);

-- -----------------------------------------------------------------------------
-- 4. ACTIVOS DE TI (tabla central de la CMDB)
--    estado    : OPERATIVO | EN_REPARACION | DE_BAJA
--    criticidad: ALTA | MEDIA | BAJA
--    codigo    : formato CI-001, CI-002, ...
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activos (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo               VARCHAR(10)  NOT NULL,
    nombre               VARCHAR(150) NOT NULL,
    tipo_id              BIGINT       NOT NULL,
    marca                VARCHAR(80),
    modelo               VARCHAR(80),
    numero_serie         VARCHAR(100),
    ubicacion_id         BIGINT       NOT NULL,
    responsable          VARCHAR(120),
    estado               VARCHAR(20)  NOT NULL,
    criticidad           VARCHAR(10)  NOT NULL DEFAULT 'MEDIA',
    fecha_compra         DATE,
    fecha_fin_garantia   DATE,
    observaciones        VARCHAR(500),
    fecha_registro       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion  TIMESTAMP,

    CONSTRAINT uq_activos_codigo UNIQUE (codigo),

    CONSTRAINT fk_activos_tipo
        FOREIGN KEY (tipo_id) REFERENCES tipos_activo (id),

    CONSTRAINT fk_activos_ubicacion
        FOREIGN KEY (ubicacion_id) REFERENCES ubicaciones (id),

    CONSTRAINT ck_activos_estado
        CHECK (estado IN ('OPERATIVO', 'EN_REPARACION', 'DE_BAJA')),

    CONSTRAINT ck_activos_criticidad
        CHECK (criticidad IN ('ALTA', 'MEDIA', 'BAJA')),

    -- Formato obligatorio del código institucional: CI-001
    CONSTRAINT ck_activos_codigo_formato
        CHECK (codigo ~ '^CI-[0-9]{3,}$'),

    -- La garantía no puede terminar antes de la compra
    CONSTRAINT ck_activos_fechas
        CHECK (fecha_fin_garantia IS NULL
               OR fecha_compra IS NULL
               OR fecha_fin_garantia >= fecha_compra)
);

-- -----------------------------------------------------------------------------
-- 5. HISTORIAL / AUDITORÍA DE CAMBIOS SOBRE ACTIVOS
--    accion: CREACION | EDICION | ELIMINACION
--    Al eliminar un activo su historial SE CONSERVA: la FK deja activo_id en
--    NULL y el detalle guarda el código y el nombre del equipo eliminado.
--    Si se elimina el usuario, el historial también se conserva (usuario_id = NULL).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS historial_activo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo_id   BIGINT,
    usuario_id  BIGINT,
    accion      VARCHAR(20)  NOT NULL,
    detalle     VARCHAR(500),
    fecha       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_historial_activo
        FOREIGN KEY (activo_id) REFERENCES activos (id) ON DELETE SET NULL,

    CONSTRAINT fk_historial_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL,

    CONSTRAINT ck_historial_accion
        CHECK (accion IN ('CREACION', 'EDICION', 'ELIMINACION'))
);

-- -----------------------------------------------------------------------------
-- 6. ÍNDICES PARA BÚSQUEDA, FILTROS Y DASHBOARD
-- -----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_activos_tipo        ON activos (tipo_id);
CREATE INDEX IF NOT EXISTS idx_activos_ubicacion   ON activos (ubicacion_id);
CREATE INDEX IF NOT EXISTS idx_activos_estado      ON activos (estado);
CREATE INDEX IF NOT EXISTS idx_activos_criticidad  ON activos (criticidad);
CREATE INDEX IF NOT EXISTS idx_activos_garantia    ON activos (fecha_fin_garantia);
CREATE INDEX IF NOT EXISTS idx_activos_nombre      ON activos (LOWER(nombre));

CREATE INDEX IF NOT EXISTS idx_historial_activo    ON historial_activo (activo_id);
CREATE INDEX IF NOT EXISTS idx_historial_fecha     ON historial_activo (fecha DESC);

COMMIT;

